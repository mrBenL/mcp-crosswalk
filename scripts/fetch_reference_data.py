"""Download the NIST OSCAL files that mcp-crosswalk vendors, and record their provenance.

Run from the project root:

    uv run python scripts/fetch_reference_data.py            # fetch every file
    uv run python scripts/fetch_reference_data.py ID [ID...] # fetch only these IDs

Uses only the standard library. Each file is verified to parse as JSON with a top-level
``catalog`` key before it is written. ``catalog/frameworks/SOURCES.md`` is rewritten with the
URL, UTC retrieval date, and SHA-256 of every vendored file; files not fetched in this run keep
the retrieval date already recorded for them, and their SHA-256 is recomputed from disk.
"""

from __future__ import annotations

import hashlib
import json
import re
import sys
import urllib.request
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FRAMEWORKS_DIR = ROOT / "catalog" / "frameworks"
TIMEOUT_SECONDS = 60

_OSCAL = "https://raw.githubusercontent.com/usnistgov/oscal-content/main/nist.gov"
_BASELINES = f"{_OSCAL}/SP800-53/rev5/json"

SOURCES: list[tuple[str, str, str]] = [
    (
        "nist-800-53r5",
        f"{_OSCAL}/SP800-53/rev5/json/NIST_SP-800-53_rev5_catalog.json",
        "nist-800-53r5/NIST_SP-800-53_rev5_catalog.json",
    ),
    (
        "nist-csf-2.0",
        f"{_OSCAL}/CSF/v2.0/json/NIST_CSF_v2.0_catalog.json",
        "nist-csf-2.0/NIST_CSF_v2.0_catalog.json",
    ),
    *[
        (
            f"nist-800-53r5-{name.lower()}",
            f"{_BASELINES}/NIST_SP-800-53_rev5_{name}-baseline-resolved-profile_catalog.json",
            f"nist-800-53r5-baselines/NIST_SP-800-53_rev5_{name}-baseline-resolved-profile_catalog.json",
        )
        for name in ("LOW", "MODERATE", "HIGH", "PRIVACY")
    ],
    (
        "nist-800-171r3",
        f"{_OSCAL}/SP800-171/rev3/json/NIST_SP800-171_rev3_catalog.json",
        "nist-800-171r3/NIST_SP800-171_rev3_catalog.json",
    ),
]

_ROW_DATE = re.compile(r"^\| `[^`]+` \| `([^`]+)` \| <[^>]+> \| (\S+) \|")


def fetch(url: str) -> bytes:
    if not url.startswith("https://"):
        raise ValueError(f"refusing non-HTTPS URL: {url}")
    request = urllib.request.Request(url, headers={"User-Agent": "mcp-crosswalk-fetch/0.2"})  # noqa: S310 - HTTPS-only, checked above
    with urllib.request.urlopen(request, timeout=TIMEOUT_SECONDS) as response:  # noqa: S310 - HTTPS-only, checked above
        data: bytes = response.read()
    return data


def verify(data: bytes, url: str) -> None:
    parsed = json.loads(data)
    if not isinstance(parsed, dict) or "catalog" not in parsed:
        raise ValueError(f"{url} did not return an OSCAL catalog (no top-level 'catalog' key)")


def recorded_dates() -> dict[str, str]:
    """Retrieval dates already recorded in SOURCES.md, keyed by relative file path."""
    sources = FRAMEWORKS_DIR / "SOURCES.md"
    if not sources.is_file():
        return {}
    dates = {}
    for line in sources.read_text(encoding="utf-8").splitlines():
        match = _ROW_DATE.match(line)
        if match:
            dates[match.group(1)] = match.group(2)
    return dates


def main(argv: list[str]) -> int:
    known = {framework for framework, _, _ in SOURCES}
    wanted = set(argv) or known
    unknown = wanted - known
    if unknown:
        print(f"unknown IDs: {', '.join(sorted(unknown))}; choose from {', '.join(sorted(known))}")
        return 2
    retrieved = datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ")
    previous = recorded_dates()
    rows: list[str] = []
    for framework, url, rel_path in SOURCES:
        target = FRAMEWORKS_DIR / rel_path
        if framework in wanted:
            print(f"Fetching {framework} ...")
            data = fetch(url)
            verify(data, url)
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
            when = retrieved
            print(f"  wrote {target.relative_to(ROOT)} ({len(data)} bytes)")
        elif target.is_file() and rel_path in previous:
            data = target.read_bytes()
            when = previous[rel_path]
        else:
            print(f"  {framework}: not vendored yet; run with this ID to fetch it")
            continue
        digest = hashlib.sha256(data).hexdigest()
        rows.append(f"| `{framework}` | `{rel_path}` | <{url}> | {when} | `{digest}` |")

    sources_md = "\n".join(
        [
            "# Vendored reference data: sources",
            "",
            "Generated by `scripts/fetch_reference_data.py`. "
            "Do not hand-edit; re-run the script to refresh.",
            "The files are NIST works (public domain in the United States) "
            "and are vendored unmodified.",
            "",
            "| Framework | File (under `catalog/frameworks/`) | URL | Retrieved (UTC) | SHA-256 |",
            "|---|---|---|---|---|",
            *rows,
            "",
        ]
    )
    (FRAMEWORKS_DIR / "SOURCES.md").write_text(sources_md, encoding="utf-8")
    print("Wrote catalog/frameworks/SOURCES.md")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
